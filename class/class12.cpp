// 对象的初始化和清理
// 1.构造函数和析构函数
// 构造函数语法：类名()    {}
// 不写返回值也不写void，函数名和类名相同，构造函数可以有参数因此可以发生重载（）变量名相同 ，程序在调用对象的时候会自动调用构造函数，无需手动调用，而且只会调用一次

// 2.析构函数语法：~类名()    {}
// 没有返回值也不写void，函数名与类名相同前面写~，不可以有参数，因此不能发生重载，程序在对象销毁之前会自动调用析构函数，无需手动调用，而且只会调用一次
#include <iostream>
using namespace std;

class person
{
    public:
    person()
    {
        cout<<"构造函数的调用";
    }
};
void test1()
{
    person p;
}
int main()
{
    test1();
}

